    /**
     * Copies a file bundled under seeders/assets into the public disk, keeping
     * the same relative path, and returns that path. Used for the building
     * picture and model as well as every destination file.
     */
    private function storeAsset(string $relativePath): string
    {
        $folder = dirname($relativePath);
        $path = Storage::disk('public')->putFileAs(
            $folder === '.' ? '' : $folder,
            new File(database_path("seeders/assets/{$relativePath}")),
            basename($relativePath),
        );

        if ($path === false) {
            throw new RuntimeException("Unable to copy the seeded asset {$relativePath} to the public disk.");
        }

        return $path;
    }
